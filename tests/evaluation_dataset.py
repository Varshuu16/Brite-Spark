"""
Structured Evaluation Dataset for BriteSpark Policy Reasoning Engine (Part 7).

Contains 21 comprehensive test cases covering direct policy retrieval, multi-clause synthesis,
temporal versioning, conflict detection, citation validation, refusal safety, and adversarial queries.
"""

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class EvaluationCase:
    """
    Structured representation of a single policy evaluation scenario.
    """
    case_id: str
    name: str
    question: str
    category: str
    expected_clause_ids: List[str]
    expected_status: Optional[str] = "UNSPECIFIED"
    expected_answer_keywords: List[str] = field(default_factory=list)
    expected_citations: List[str] = field(default_factory=list)
    expected_refusal: bool = False
    expected_conflict: bool = False
    mock_response: Optional[str] = None
    description: str = ""

    def to_dict(self) -> Dict[str, Any]:
        return {
            "case_id": self.case_id,
            "name": self.name,
            "question": self.question,
            "category": self.category,
            "expected_clause_ids": self.expected_clause_ids,
            "expected_status": self.expected_status,
            "expected_answer_keywords": self.expected_answer_keywords,
            "expected_citations": self.expected_citations,
            "expected_refusal": self.expected_refusal,
            "expected_conflict": self.expected_conflict,
            "description": self.description,
        }


